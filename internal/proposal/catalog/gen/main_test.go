// TestGeneratedCatalogIsFresh reruns the generator on the real schema and metadata and compares
// with the committed file (D-066). A stale file means someone changed the schema or the metadata
// without regenerating.
func TestGeneratedCatalogIsFresh(t *testing.T) {
	t.Parallel()
	schema, err := os.ReadFile(realSchema)
	if err != nil {
		t.Fatal(err)
	}
	meta, err := os.ReadFile(realMeta)
	if err != nil {
		t.Fatal(err)
	}
	want, err := generate(schema, meta)
	if err != nil {
		t.Fatalf("generate on the real inputs: %v", err)
	}
	got, err := os.ReadFile(realOut)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Fatal("internal/proposal/catalog/catalog_gen.go is stale: run `make generate-catalog` and commit the result")
	}
}

func TestGenerateIsDeterministicAndValidGo(t *testing.T) {
	t.Parallel()
	a, err := generate([]byte(miniSchema), []byte(miniMeta))
	if err != nil {
		t.Fatal(err)
	}
	b, _ := generate([]byte(miniSchema), []byte(miniMeta))
	if !bytes.Equal(a, b) {
		t.Error("two runs differ")
	}
	if !strings.HasPrefix(string(a), "// Code generated by catalog/gen. DO NOT EDIT.\n") {
		t.Errorf("missing generated header:\n%s", a)
	}
	if _, err := parser.ParseFile(token.NewFileSet(), "catalog_gen.go", a, parser.AllErrors); err != nil {
		t.Errorf("generated code does not parse: %v", err)
	}
}

// A small schema and matching metadata: one root field per kind, one relation with a nested child.
const miniSchema = `
input StringFilter { eq: String ne: String in: [String!] }
input IntFilter { eq: Int gt: Int lte: Int in: [Int!] }
input BooleanFilter { eq: Boolean ne: Boolean }
input DateTimeFilter { eq: TimeValue gte: TimeValue in: [TimeValue!] }

input ItemFilter {
  and: [ItemFilter!]
  or: [ItemFilter!]
  not: ItemFilter
  qty: IntFilter
  at: DateTimeFilter
}
input ItemRelationFilter { some: ItemFilter none: ItemFilter }

input CustomerFilter {
  and: [CustomerFilter!]
  or: [CustomerFilter!]
  not: CustomerFilter
  tier: StringFilter
  vip: BooleanFilter
  "Customers by items."
  items: ItemRelationFilter
}
`

const miniMeta = `
entities:
  customer:
    description: A customer.
    relations:
      items: {description: The items.}
    fields:
      tier: {description: The tier., closed: [A, B]}
      vip: {description: Is vip.}
  items:
    description: One item.
    fields:
      qty: {description: Quantity.}
      at: {description: When.}
`

func TestGenerateMini(t *testing.T) {
	t.Parallel()
	out, err := generate([]byte(miniSchema), []byte(miniMeta))
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		`Name: "tier", Kind: KindString, Ops: []dsl.Op{dsl.OpEq, dsl.OpNe, OpIn}, Closed: []string{"A", "B"}, Description: "The tier."`,
		`Name: "vip", Kind: KindBool, Ops: []dsl.Op{dsl.OpEq, dsl.OpNe}, Description: "Is vip."`,
		`Name: "qty", Kind: KindInt, Ops: []dsl.Op{dsl.OpEq, dsl.OpGt, dsl.OpLte, OpIn}`,
		`Name: "at", Kind: KindDateTime, Ops: []dsl.Op{dsl.OpEq, dsl.OpGte, OpIn}`,
		`Quantifiers: []dsl.Quantifier{dsl.Some, dsl.None}`,
		`Name:        "items"`,
	} {
		if !strings.Contains(string(out), want) {
			t.Errorf("output lacks %q\n%s", want, out)
		}
	}
	if strings.Contains(string(out), `Name: "and"`) {
		t.Error("and/or/not leaked into the catalog")
	}
}

// TestGenerateDrift: every disagreement between schema and metadata fails the generator, and the
// error names the culprit (D-066).
func TestGenerateDrift(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name         string
		schema, meta string // replacements applied to the mini inputs: old, new pairs "old=>new"
		want         string
	}{
		{"missing field description", "", "      vip: {description: Is vip.}=>", `customer.vip has no description`},
		{"empty field description", "", "Is vip.=>", `customer.vip has no description`},
		{"missing entity description", "", "    description: One item.=>", `entity "items" has no description`},
		{"missing relation description", "", "      items: {description: The items.}=>      items: {}", `customer.items (relation) has no description`},
		{"extra metadata field", "", "      vip: {description: Is vip.}=>      vip: {description: Is vip.}\n      ghost: {description: Gone.}", `customer: metadata field "ghost" has no counterpart`},
		{"extra metadata relation", "", "      items: {description: The items.}=>      items: {description: The items.}\n      ghosts: {description: Gone.}", `metadata relation "ghosts" has no counterpart`},
		{"extra metadata entity", "", "  items:\n    description: One item.=>  ghosts:\n    description: Nope.\n  items:\n    description: One item.", `metadata entity "ghosts" has no counterpart`},
		{"schema field without metadata", "  vip: BooleanFilter=>  vip: BooleanFilter\n  extra: IntFilter", "", `customer.extra has no description`},
		{"closed list on an Int field", "", "qty: {description: Quantity.}=>qty: {description: Quantity., closed: [1, 2]}", `items.qty: a closed list needs a String field, not Int`},
		{"closed list on a Bool field", "", "vip: {description: Is vip.}=>vip: {description: Is vip., closed: [yes]}", `customer.vip: a closed list needs a String field`},
		{"empty closed list", "", "closed: [A, B]=>closed: []", `customer.tier: closed list is empty`},
		{"repeated closed value", "", "closed: [A, B]=>closed: [A, A]", `closed list repeats "A"`},
		{"unknown filter type", "  vip: BooleanFilter=>  vip: Mystery", "", `customer.vip: unknown filter type "Mystery"`},
		{"scalar instead of a filter", "  vip: BooleanFilter=>  vip: Boolean", "", `unknown filter type "Boolean"`},
		{"list-typed filter field", "  vip: BooleanFilter=>  vip: [BooleanFilter!]", "", `customer.vip: list-typed filter fields are not supported`},
		{"unsupported operator", "input IntFilter { eq: Int=>input IntFilter { like: Int eq: Int", "", `operator "like" of IntFilter is not supported`},
		{"unsupported quantifier", "input ItemRelationFilter { some: ItemFilter=>input ItemRelationFilter { most: ItemFilter some: ItemFilter", "", `quantifier "most" of ItemRelationFilter is not supported`},
		{"relation with two child types", "none: ItemFilter }=>none: CustomerFilter }", "", `must all take one filter input`},
		{"relation filter undefined", "  items: ItemRelationFilter=>  items: GhostRelationFilter", "", `relation filter "GhostRelationFilter" is not defined`},
		{"relation cycle", "  qty: IntFilter\n=>  qty: IntFilter\n  back: ItemRelationFilter\n", "      qty: {description: Quantity.}=>      qty: {description: Quantity.}\n    relations:\n      back: {description: Back.}", `filter ItemFilter is its own ancestor`},
		{"no root filter", "input CustomerFilter {=>input OtherFilter {", "", `no input CustomerFilter`},
		{"unknown metadata key", "", "    description: A customer.=>    description: A customer.\n    colour: red", `field colour not found`},
		{"bad yaml", "", "entities:=>entities: [", `metadata:`},
		{"bad schema", "input CustomerFilter {=>input CustomerFilter {{", "", `schema:`},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			schema, meta := apply(t, miniSchema, tc.schema), apply(t, miniMeta, tc.meta)
			out, err := generate([]byte(schema), []byte(meta))
			if err == nil {
				t.Fatalf("generate succeeded, want an error containing %q\n%s", tc.want, out)
			}
			if out != nil || !strings.Contains(err.Error(), tc.want) {
				t.Errorf("error = %v\nwant it to contain %q", err, tc.want)
			}
		})
	}
}

// apply performs the "old=>new" replacement; empty means no change.
func apply(t *testing.T, base, repl string) string {
	t.Helper()
	if repl == "" {
		return base
	}
	old, repNew, ok := strings.Cut(repl, "=>")
	if !ok || !strings.Contains(base, old) {
		t.Fatalf("test replacement %q does not match the base", repl)
	}
	return strings.Replace(base, old, repNew, 1)
}

func TestGenerateReportsAllProblems(t *testing.T) {
	t.Parallel()
	meta := apply(t, apply(t, miniMeta, "      vip: {description: Is vip.}=>"), "      qty: {description: Quantity.}=>")
	_, err := generate([]byte(miniSchema), []byte(meta))
	if err == nil || !strings.Contains(err.Error(), "customer.vip has no description") || !strings.Contains(err.Error(), "items.qty has no description") {
		t.Errorf("error = %v", err)
	}
}

func TestRunWritesFile(t *testing.T) {
	t.Parallel()
	out := t.TempDir() + "/catalog_gen.go"
	if err := run(realSchema, realMeta, out); err != nil {
		t.Fatal(err)
	}
	got, _ := os.ReadFile(out)
	want, _ := os.ReadFile(realOut)
	if !bytes.Equal(got, want) {
		t.Error("run output differs from the committed catalog")
	}
	if err := run("missing.graphqls", realMeta, out); err == nil {
		t.Error("missing schema must fail")
	}
	if err := run(realSchema, "missing.yaml", out); err == nil {
		t.Error("missing metadata must fail")
	}
}
