func TestLockFileIsFresh(t *testing.T) {
	t.Parallel()
	b, err := os.ReadFile(LockFile)
	if err != nil {
		t.Fatalf("read %s: %v (run `make generate-prompts`)", LockFile, err)
	}
	committed, err := ParseLock(b)
	if err != nil {
		t.Fatal(err)
	}
	for _, e := range committed.Check(CurrentLock()) {
		t.Error(e)
	}
	if got := CurrentLock().Marshal(); string(got) != string(b) {
		t.Errorf("%s differs from the generated bytes: run `make generate-prompts`", LockFile)
	}
}

func entry(name, version, sha string) LockEntry {
	return LockEntry{Name: name, Version: version, SHA256: sha}
}

func TestLockCheck(t *testing.T) {
	t.Parallel()
	cur := Lock{Prompts: []LockEntry{entry("a", "1.0.0", "h1"), entry("b", "2.1.0", "h2")}}
	tests := []struct {
		name      string
		committed Lock
		want      []string // substrings, one per problem
		bump      bool
	}{
		{"fresh", cur, nil, false},
		{"hash moved, version same", Lock{Prompts: []LockEntry{entry("a", "1.0.0", "other"), entry("b", "2.1.0", "h2")}},
			[]string{"raise version in a/manifest.yaml"}, true},
		{"version bumped, lock not regenerated", Lock{Prompts: []LockEntry{entry("a", "0.9.0", "h1"), entry("b", "2.1.0", "h2")}},
			[]string{"a is stale"}, false},
		{"missing entry", Lock{Prompts: []LockEntry{entry("a", "1.0.0", "h1")}}, []string{"b is not in"}, false},
		{"removed prompt", Lock{Prompts: []LockEntry{entry("a", "1.0.0", "h1"), entry("b", "2.1.0", "h2"), entry("c", "1.0.0", "h3")}},
			[]string{"which no longer exists"}, false},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			errs := tt.committed.Check(cur)
			if len(errs) != len(tt.want) {
				t.Fatalf("problems = %v, want %d", errs, len(tt.want))
			}
			for i, w := range tt.want {
				if !strings.Contains(errs[i].Error(), w) {
					t.Errorf("problem %d = %q, want it to contain %q", i, errs[i], w)
				}
				if got := errors.Is(errs[i], ErrVersionNotBumped); got != tt.bump {
					t.Errorf("errors.Is(ErrVersionNotBumped) = %v, want %v", got, tt.bump)
				}
			}
		})
	}
}

func TestLockRegenerate(t *testing.T) {
	t.Parallel()
	cur := Lock{Prompts: []LockEntry{entry("a", "1.1.0", "h1")}}
	// A new version, a new prompt and a first run are all fine.
	for _, old := range []Lock{{}, {Prompts: []LockEntry{entry("a", "1.0.0", "x")}}, {Prompts: []LockEntry{entry("a", "1.1.0", "h1")}}} {
		got, err := old.Regenerate(cur)
		if err != nil || len(got.Prompts) != 1 || got.Prompts[0] != cur.Prompts[0] {
			t.Errorf("Regenerate(%v) = %v, %v", old, got, err)
		}
	}
	// The same version with another hash is the bug the lock exists for.
	_, err := Lock{Prompts: []LockEntry{entry("a", "1.1.0", "old")}}.Regenerate(cur)
	if !errors.Is(err, ErrVersionNotBumped) {
		t.Errorf("err = %v, want ErrVersionNotBumped", err)
	}
}

