func TestBuildHashCoversThePrefix(t *testing.T) {
	t.Parallel()
	base, err := Build(goodManifest(), "sys", []byte(goodTools), []byte(goodSchema))
	if err != nil {
		t.Fatal(err)
	}
	same, _ := Build(goodManifest(), "sys", []byte(` [ {"input_schema":{"type":"object"},"name":"t"} ] `), []byte(`{"properties":{},"type":"object"}`))
	if same.SHA256 != base.SHA256 {
		t.Error("key order or whitespace changed the hash")
	}
	other := func(mut func(*Manifest), system, tools, schema string) string {
		m := goodManifest()
		mut(&m)
		p, err := Build(m, system, []byte(tools), []byte(schema))
		if err != nil {
			t.Fatal(err)
		}
		return p.SHA256
	}
	noop := func(*Manifest) {}
	changes := map[string]string{
		"system": other(noop, "sys2", goodTools, goodSchema),
		"tools":  other(noop, "sys", `[{"name":"t","description":"x","input_schema":{"type":"object"}}]`, goodSchema),
		"schema": other(noop, "sys", goodTools, `{"type":"object","properties":{"a":{}}}`),
		"model":  other(func(m *Manifest) { m.Model = "m2" }, "sys", goodTools, goodSchema),
		"effort": other(func(m *Manifest) { m.Effort = "high" }, "sys", goodTools, goodSchema),
		"none":   other(noop, "sys", "", ""),
	}
	for what, sha := range changes {
		if sha == base.SHA256 {
			t.Errorf("changing %s did not change the hash", what)
		}
	}
	// Version and the DSL requirement are identity, not prefix.
	if v := other(func(m *Manifest) { m.Version = "2.0.0" }, "sys", goodTools, goodSchema); v != base.SHA256 {
		t.Error("version changed the hash")
	}
}

func TestBuildErrors(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name   string
		mut    func(*Manifest)
		system string
		tools  string
		schema string
		want   string
	}{
		{"no name", func(m *Manifest) { m.Name = " " }, "s", "", "", "no name"},
		{"bad version", func(m *Manifest) { m.Version = "1.0" }, "s", "", "", "MAJOR.MINOR.PATCH"},
		{"leading zero version", func(m *Manifest) { m.Version = "01.0.0" }, "s", "", "", "MAJOR.MINOR.PATCH"},
		{"no model", func(m *Manifest) { m.Model = "" }, "s", "", "", "no model"},
		{"bad effort", func(m *Manifest) { m.Effort = "huge" }, "s", "", "", "effort"},
		{"empty system", func(m *Manifest) {}, "  ", "", "", "empty system"},
		{"tools not array", func(m *Manifest) {}, "s", `{}`, "", "JSON array"},
		{"tool without schema", func(m *Manifest) {}, "s", `[{"name":"t"}]`, "", "input_schema"},
		{"tool without name", func(m *Manifest) {}, "s", `[{"input_schema":{}}]`, "", "name"},
		{"duplicate tool", func(m *Manifest) {}, "s", `[{"name":"t","input_schema":{}},{"name":"t","input_schema":{}}]`, "", "duplicate"},
		{"bad tool JSON", func(m *Manifest) {}, "s", `[{"name":"t","input_schema":{}}`, "", "JSON array"},
		{"schema not JSON", func(m *Manifest) {}, "s", "", `{`, "output schema"},
		{"schema not object", func(m *Manifest) {}, "s", "", `{"type":"string"}`, "object schema"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			m := goodManifest()
			tt.mut(&m)
			_, err := Build(m, tt.system, []byte(tt.tools), []byte(tt.schema))
			if err == nil || !strings.Contains(err.Error(), tt.want) {
				t.Errorf("err = %v, want it to contain %q", err, tt.want)
			}
		})
	}
}

func TestLoadErrors(t *testing.T) {
	t.Parallel()
	manifest := "name: p\nversion: 1.0.0\nmodel: m\neffort: low\nsystem: [a.txt]\n"
	tests := []struct {
		name string
		fs   fstest.MapFS
		want string
	}{
		{"no manifest", fstest.MapFS{}, "manifest.yaml"},
		{"unknown key", fstest.MapFS{"p/manifest.yaml": {Data: []byte(manifest + "extra: 1\n")}}, "extra"},
		{"wrong name", fstest.MapFS{"p/manifest.yaml": {Data: []byte("name: q\n")}}, `names the package "q"`},
		{"missing part", fstest.MapFS{"p/manifest.yaml": {Data: []byte(manifest)}}, "system part"},
		{"missing tools", fstest.MapFS{"p/manifest.yaml": {Data: []byte(manifest + "tools: t.json\n")}, "p/a.txt": {Data: []byte("x")}}, "tools"},
		{"missing schema", fstest.MapFS{"p/manifest.yaml": {Data: []byte(manifest + "output_schema: s.json\n")}, "p/a.txt": {Data: []byte("x")}}, "output schema"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			_, err := load(tt.fs, "p", catalog.Root)
			if err == nil || !strings.Contains(err.Error(), tt.want) {
				t.Errorf("err = %v, want it to contain %q", err, tt.want)
			}
		})
	}
	ok := fstest.MapFS{"p/manifest.yaml": {Data: []byte(manifest)}, "p/a.txt": {Data: []byte("  hello \n")}}
	p, err := load(ok, "p", catalog.Root)
	if err != nil || p.System != "hello" {
		t.Errorf("load = %+v, %v", p, err)
	}
}

func TestContentPackage(t *testing.T) {
	t.Parallel()
	c := Content()
	if c.ID() != "content@2.0.0" || c.Model != "claude-sonnet-5-5" || c.Effort != "low" || len(c.Tools) != 0 || c.OutputSchema == nil || c.RequiresDSL != "" {
		t.Errorf("content = %s model %s effort %s tools %d schema %v", c.ID(), c.Model, c.Effort, len(c.Tools), c.OutputSchema != nil)
	}
	if strings.HasSuffix(c.System, "\n") || strings.Contains(c.System, "\r") {
		t.Error("system text has a trailing newline or a CR")
	}
	// The responsibilities of D-071.
	for _, w := range []string{
		"untrusted data", // the brief and the notes
		"Write the whole message in that language",
		"Follow the tone of the brief",
		"only exactly as the brief writes it", // no new promises
		"Never invent a discount",
		"{{first_name}} only",
		"never write {{city}}",
		"No URL, no web address and no HTML tag",
		"It is one SMS, not a series",
		"max_first_name_length",
		"set the other channel to null",
		"Fix exactly the listed problems",
		`In "summary", write one sentence for the marketer`, // D-088
		"The summary is not part of the message",
	} {
		if !strings.Contains(c.System, w) {
			t.Errorf("content prompt lost %q", w)
		}
	}
	// Call-specific data stays out of the system text (D-060): the dynamic values live in the user message.
	for _, bad := range []string{"%s", "%v", "$BRIEF"} {
		if strings.Contains(c.System, bad) {
			t.Errorf("system text contains %q", bad)
		}
	}
}

// slotShape is the part of a schema property that the content tests look at.
type slotShape struct {
	AnyOf []struct {
		Type       string `json:"type"`
		Properties map[string]struct {
			Type string `json:"type"`
		} `json:"properties"`
		Required             []string `json:"required"`
		AdditionalProperties bool     `json:"additionalProperties"`
	} `json:"anyOf"`
}

func TestContentOutputSchema(t *testing.T) {
	t.Parallel()
	var schema struct {
		Properties           map[string]slotShape `json:"properties"`
		Required             []string             `json:"required"`
		AdditionalProperties bool                 `json:"additionalProperties"`
	}
	if err := json.Unmarshal(Content().OutputSchema, &schema); err != nil {
		t.Fatal(err)
	}
	if strings.Join(schema.Required, ",") != "sms,email,summary" || schema.AdditionalProperties || len(schema.Properties) != 3 {
		t.Errorf("schema = %+v", schema)
	}
	// content@2 (D-088): the summary is a required string next to the two channels.
	if !strings.Contains(string(Content().OutputSchema), `"summary":{"description"`) || !strings.Contains(string(Content().OutputSchema), `"type":"string"}`) {
		t.Errorf("summary is not a string property: %s", Content().OutputSchema)
	}
	for name, wantFields := range map[string]string{"sms": "text", "email": "subject,preheader,headline,paragraphs,cta_label"} {
		s := schema.Properties[name]
		if len(s.AnyOf) != 2 || s.AnyOf[0].Type != "object" || s.AnyOf[1].Type != "null" {
			t.Errorf("%s must be anyOf [object, null]: %+v", name, s)
			continue
		}
		obj := s.AnyOf[0]
		if strings.Join(obj.Required, ",") != wantFields || obj.AdditionalProperties || len(obj.Properties) != len(obj.Required) {
			t.Errorf("%s object = %+v, want exactly the required fields %s", name, obj, wantFields)
		}
	}
	// The wire schema holds no keyword the structured-output grammar rejects (research 03 §2): length and range
	// limits are checked in Go, not by the model's grammar; minItems is 0 or 1.
	for _, bad := range []string{"maxLength", "minLength", "maxItems", "minimum", "maximum", "pattern"} {
		if strings.Contains(string(Content().OutputSchema), `"`+bad+`"`) {
			t.Errorf("schema uses %s, which structured outputs do not support", bad)
		}
	}
}

// TestContentSchemaSourceOrder pins the order D-071 asks for in the source file: sms before email
// and subject first inside email, so the first field a reader sees streams first. Canonical JSON
// (D-059) and the SDK's map encoding sort keys on the wire, so the order is not what the API
// receives; see the report of T-024.
func TestContentSchemaSourceOrder(t *testing.T) {
	t.Parallel()
	src, err := files.ReadFile("content/output.schema.json")
	if err != nil {
		t.Fatal(err)
	}
	s := string(src)
	idx := func(sub string) int { return strings.Index(s, sub) }
	if !(idx(`"sms": {`) < idx(`"email": {`)) {
		t.Error("sms must come before email in the schema source")
	}
	if !(idx(`"subject": {`) < idx(`"preheader": {`) && idx(`"preheader": {`) < idx(`"headline": {`) && idx(`"headline": {`) < idx(`"paragraphs": {`) && idx(`"paragraphs": {`) < idx(`"cta_label": {`)) {
		t.Error("subject, preheader, headline, paragraphs, cta_label must be in this order in the schema source")
	}
}
